// Removes the Gemini sparkle from the site's Gemini-generated photos by cropping it out:
// each photo is zoomed slightly so the bottom-right corner that carries the mark falls outside
// the frame. The aspect ratio is kept exactly and nothing is upscaled, so there is no blur.
//
// Source images are read from a git commit that still holds the untouched optimized files,
// so the crop is never applied twice. Pass another ref with SOURCE_REF=<commit> if needed.
//
// Usage:
//   node scripts/remove-image-watermark.mjs          # crop the 26 files in place
//   node scripts/remove-image-watermark.mjs --dry    # report only
// Run after rebuild-hd-assets.mjs (then commit), since the source images still carry the mark.
import { execFileSync } from 'node:child_process';
import fs from 'node:fs';
import path from 'node:path';
import sharp from 'sharp';

sharp.cache(false); // Windows: don't keep files open, so they can be overwritten in place

const ROOT = process.cwd();
const DRY = process.argv.includes('--dry');
const SOURCE_REF = process.env.SOURCE_REF || 'e7e9620';

// Only images generated by Gemini carry the mark (named banners, real photos and the poolside villa don't).
const GEMINI_IMAGES = [
  'architectural-hardware-fittings-stainless', 'architectural-villa-coastal-estate', 'corporate-spider-fitting-canopy',
  'decorative-fluted-reeded-glass', 'led-mirror-bathroom-vanity', 'partitions-corporate-conference-room',
  'railing-continuous-base-channel', 'railing-floating-staircase-glass', 'railing-terrace-spigots-balcony',
  'retail-storefront-curtain-wall', 'shower-enclosure-frameless-corner', 'shower-enclosure-frameless-walkin',
  'structural-glazing-double-height-villa', 'table-top-circular-beveled-glass', 'toughened-glass-standoff-mount',
  'hardware-balustrade-railing-mounts', 'hardware-commercial-entrance-doors', 'hardware-door-controls-patch-fittings',
  'hardware-shower-cubicle-hinge', 'hardware-shower-sliding-enclosure', 'hardware-slim-partition-profiles',
  'processing-cnc-edge-polishing', 'processing-fluted-decorative-glass', 'processing-specialty-glass-finishes',
  'processing-tempering-furnace-line', 'processing-waterjet-hole-drilling',
];

// Mark centre distance from the right and bottom edges, and its width, by output size.
const markOf = (w, h) => (w >= 2000 ? (h >= 1600 ? { off: 112, size: 120 } : { off: 97, size: 104 }) : { off: 121, size: 60 });

for (const name of GEMINI_IMAGES) {
  const rel = `public/images/optimized/${name}.webp`;
  const original = execFileSync('git', ['show', `${SOURCE_REF}:${rel}`], { cwd: ROOT, maxBuffer: 64 * 1024 * 1024 });
  const { width: W, height: H } = await sharp(original).metadata();
  const { off, size } = markOf(W, H);
  // Everything from the mark's outer edge (incl. its soft glow) plus a safety margin goes.
  const cut = Math.ceil(off + size * 0.75 + 10);

  // Trim the right side or the bottom, whichever keeps more of the photo, keeping the aspect ratio.
  const byWidth = (W - cut) / W;
  const byHeight = (H - cut) / H;
  const k = Math.max(byWidth, byHeight);
  const w = Math.floor(W * k);
  const h = Math.floor(H * k);
  const left = byWidth >= byHeight ? 0 : Math.floor((W - w) / 2);
  const top = byWidth >= byHeight ? Math.floor((H - h) / 2) : 0;

  console.log(`${name.padEnd(42)} ${W}x${H} -> ${w}x${h}  (zoom ${(1 / k).toFixed(3)}, trims ${byWidth >= byHeight ? 'right' : 'bottom'})`);
  if (DRY) continue;
  const buf = await sharp(original)
    .extract({ left, top, width: w, height: h })
    .webp({ quality: 92, effort: 6, smartSubsample: true })
    .toBuffer();
  fs.writeFileSync(path.join(ROOT, rel), buf);
}
console.log(`${GEMINI_IMAGES.length} images ${DRY ? 'checked' : 'cropped'} (source: ${SOURCE_REF})`);
